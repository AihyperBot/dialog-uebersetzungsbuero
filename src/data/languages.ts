export function foldLanguage(value: string): string {
  return value
    .toLocaleLowerCase("de")
    .replace(/ß/g, "ss")
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "");
}

export function languageInitial(name: string): string {
  const folded = foldLanguage(name);
  const first = folded.charAt(0).toUpperCase();
  return /[A-Z]/.test(first) ? first : "#";
}
